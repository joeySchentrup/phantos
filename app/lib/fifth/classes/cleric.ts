/** A domain's always-prepared spells: one feature at each of levels 1, 3, 5, 7 and 9, naming the two it gives. */
function domainSpells(domain: string, name: string, spells: Record<number, string[]>): SubclassFeature[] {
  return Object.entries(spells).map(([level, names]) => ({
    level: Number(level),
    key: `${domain}-domain-spells-${level}`,
    name: `${name} Domain Spells`,
    text: `${names.join(" and ")} are always prepared for you, and don't count against the spells you prepare each day.`,
    grants: { spells: names.map(keyOf) },
  }));
}

/** Divine Strike at 8th, with the damage the domain deals; the 14th-level rise to 2d8 is in the text. */
function divineStrike(damage: string): SubclassFeature {
  return {
    level: 8,
    key: "divine-strike",
    name: "Divine Strike",
    text: `Once on each of your turns when you hit with a weapon attack, deal an extra 1d8 ${damage} damage; 2d8 from 14th level.`,
  };
}

