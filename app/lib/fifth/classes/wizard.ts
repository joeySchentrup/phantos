/** The savant feature every Player's Handbook school opens with. */
function savant(key: string, school: string, article: "a" | "an"): SubclassFeature {
  return {
    level: 2,
    key: `${key}-savant`,
    name: `${school} Savant`,
    text: `The gold and time you spend to copy ${article} ${school.toLowerCase()} spell into your spellbook are halved.`,
  };
}

