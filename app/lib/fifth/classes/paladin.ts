/** An oath's spells at one level: always prepared, and not counted against the spells prepared. */
function oathSpells(oath: string, level: number, names: [string, string]): SubclassFeature {
  return {
    level,
    key: `${oath}-oath-spells-${level}`,
    name: "Oath Spells",
    text: `You always have ${names[0]} and ${names[1]} prepared. They don't count against the spells you can prepare.`,
    grants: { spells: names.map(keyOf) },
  };
}

